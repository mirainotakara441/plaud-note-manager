/** 適合スコアの読み方。UI とプロンプトで表現を揃えるためここに一元化する。 */
export const SCORE_BANDS = [
  { min: 85, label: "本命候補", tone: "emerald" },
  { min: 70, label: "検討に値する", tone: "sky" },
  { min: 55, label: "情報として持っておく", tone: "amber" },
  { min: 0, label: "見送り", tone: "slate" },
] as const;

export function scoreBand(score: number | null | undefined) {
  if (score === null || score === undefined) {
    return { min: 0, label: "未採点", tone: "slate" as const };
  }
  return SCORE_BANDS.find((b) => score >= b.min) ?? SCORE_BANDS[SCORE_BANDS.length - 1];
}
