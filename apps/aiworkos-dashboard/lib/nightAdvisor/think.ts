export type Insight = {
  kind: "改善" | "横断" | "異議" | "問い" | "継続";
  title: string;
  body: string;
  evidence: { source_type: string; title: string; event_date: string }[];
  related_orgs: string[];
  /** 過去の示唆を引き継いだ場合、その id。新規なら空文字。 */
  continues_id: string;
};

export type ThinkResult = {
  insights: Insight[];
  /** 今晩は言うことが無い場合の理由。件数が少ないときに埋めさせる。 */
  note: string;
};

