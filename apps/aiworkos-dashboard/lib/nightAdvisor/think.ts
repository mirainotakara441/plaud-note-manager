// 夜間参謀の「考える」側。材料を受け取って示唆を作る。
//
// ■ 既存の毎朝の参謀（lib/advisor/）とは別物
//   あちらはルールベースで、作法は「事実だけ書く／原因は断定しない／
//   判定できないものは判定しない」。2026-08-03の歩数の件で、原因を断定していたら
//   真逆の結論になっていたという実害から生まれた規律で、これは一切変えない。
//
//   こちらは仮説の層。踏み込んで言う代わりに、
//     ・必ず「仮説」と分かる形で出す
//     ・根拠（どの材料から言っているか）を必ず付ける
//   の2つで担保する。断定を許す代わりに、検証可能にする。
//
// ■ 異議（オブジェクション）を必須枠にしている理由
//   2026-09-12の総点検で全システムプロンプトを読んだが、吉井さんの判断に
//   異議を唱えろと指示している箇所は1つも無かった。全ルートが「資料の事実のみ」
//   「憶測で創作するな」で縛られており、精度としては正しいが、反対意見や別の筋を
//   出す余地を構造的に封じている。枠を切らないとモデルは安全側に寄り、
//   当たり障りのないことしか言わない。

import { structured, retryOnceOnTransient } from "@/lib/llm";
